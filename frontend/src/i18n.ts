export function formatDate(iso: string, lang: Lang): string {
  const d = new Date(iso + "T12:00:00");
  return d.toLocaleDateString(lang === "es" ? "es-US" : "en-US", {
    weekday: "long", month: "long", day: "numeric",
  });
}
